/** @fileoverview Real input/module/view reference pointing preserves the editing origin and native code execution. */
import { expect, it } from "vitest";
import { CalcViewController } from "./calc-view-controller";
import { ScAddress } from "../../inc/address";
import { ScInputMode } from "../../inc/global";
it("inserts and replaces clicked references without committing or moving the edit origin", /** Native selected reference replacement changes only the real draft. @returns Nothing. */ () => {
  const controller = new CalcViewController();
  controller.Select(2, 2);
  controller.StartInput(ScInputMode.SC_INPUT_TOP, "=");
  expect(controller.PointReference(new ScAddress(0, 0, 0))).toBe(true);
  expect(controller.Input()).toBe("=A1");
  expect(controller.Position().GetVars()).toEqual([2, 2, 0]);
  expect(controller.shell.GetUndoManager().GetUndoActionCount()).toBe(0);
  controller.DragReference(new ScAddress(1, 2, 0));
  expect(controller.Input()).toBe("=A1:B3");
  expect(controller.inputSelection).toEqual([1, 6]);
  controller.PointReference(new ScAddress(3, 4, 0));
  expect(controller.Input()).toBe("=D5");
  controller.inputHandler.PrepareReferenceInput();
  controller.ChangeInput(controller.Input() + "+");
  controller.PointReference(new ScAddress(0, 1, 0));
  expect(controller.Input()).toBe("=D5+A2");
  controller.shell.GetDocument().SetValue(new ScAddress(3, 4, 0), 7);
  controller.shell.GetDocument().SetValue(new ScAddress(0, 1, 0), 3);
  expect(controller.Commit()).toBe(true);
  expect(controller.shell.GetDocument().GetValue(new ScAddress(2, 2, 0))).toBe(10);
  expect(controller.shell.Undo()).toBe(true);
  expect(controller.shell.Redo()).toBe(true);
  controller.Close();
});
it("orders backward drag references,appends native arguments and protects the leading equals", /** Native module ordering and input-handler selection rules survive actual controller dispatch. @returns Nothing. */ () => {
  const controller = new CalcViewController();
  expect(controller.PointReference(new ScAddress())).toBe(false);
  controller.StartInput(ScInputMode.SC_INPUT_TYPE, "=SUM(");
  controller.PointReference(new ScAddress(2, 3, 0));
  controller.DragReference(new ScAddress());
  expect(controller.Input()).toBe("=SUM(A1:C4");
  controller.PointReference(new ScAddress(4, 4, 0), false, true);
  expect(controller.Input()).toBe("=SUM(A1:C4;E5");
  controller.PointReference(new ScAddress(5, 5, 0), true);
  expect(controller.Input()).toBe("=SUM(A1:C4;E5:F6");
  controller.SetInputSelection(0, 1);
  controller.PointReference(new ScAddress(1, 1, 0));
  expect(controller.Input()).toBe("=SUM(A1:C4;E5:F6");
  controller.Cancel();
  expect(controller.ReferenceRange()).toBe(null);
  controller.Close();
});

it("retains the native reference endpoint across operator input and ignores top/left boundary arrows", /** Source MoveCursorRel reads the reference end before starting the next reference. @returns Nothing. */ () => {
  const c = new CalcViewController();
  c.StartInput(ScInputMode.SC_INPUT_TYPE, "=");
  c.NavigateReference(-1, 0, false);
  c.NavigateReference(0, -1, false);
  expect(c.Input()).toBe("=");
  c.PointReference(new ScAddress(2, 2, 0));
  c.inputHandler.PrepareReferenceInput();
  c.ChangeInput(c.Input() + "+");
  expect(c.ReferenceRange()?.aEnd.GetVars()).toEqual([2, 2, 0]);
  c.NavigateReference(1, 0, false);
  expect(c.Input()).toBe("=C3+D3");
  expect(c.Position().GetVars()).toEqual([0, 0, 0]);
  c.Cancel();
  c.Close();
});
it("retains native reference boundary clamping and hidden-axis movement", /** Actual source document limits and hidden spans drive reference navigation. @returns Nothing. */ () => {
  const c = new CalcViewController(),
    doc = c.shell.GetDocument();
  c.Select(doc.MaxCol(), doc.MaxRow());
  c.StartInput(ScInputMode.SC_INPUT_TYPE, "=");
  expect(c.ReferenceRange()).toBe(null);
  c.NavigateReference(1, 0, false);
  expect(c.Input()).toBe("=XFD1048576");
  c.NavigateReference(0, 1, false);
  c.NavigateReference(0, 0, false);
  expect(c.Input()).toBe("=XFD1048576");
  c.Cancel();
  c.Select(0, 0);
  c.StartInput(ScInputMode.SC_INPUT_TYPE, "=");
  c.NavigateReference(-1, 1, false);
  expect(c.Input()).toBe("=A2");
  c.Cancel();
  c.Select(0, 0);
  doc.SetColHidden(1, 2, 0, true);
  doc.SetRowHidden(1, 2, 0, true);
  c.StartInput(ScInputMode.SC_INPUT_TYPE, "=");
  c.NavigateReference(1, 0, false);
  expect(c.Input()).toBe("=D1");
  c.NavigateReference(0, 1, false);
  expect(c.Input()).toBe("=D4");
  c.NavigateReference(-1, 0, false);
  expect(c.Input()).toBe("=A4");
  c.NavigateReference(0, -1, false);
  expect(c.Input()).toBe("=A1");
  c.Cancel();
  c.Close();
});

it("replaces an active draft while preserving existing-content semantics and valid UTF16 caret bounds", /** Actual edit-command replacement is distinct from a focus-only mode transition. @returns Nothing. */ () => {
  const c = new CalcViewController();
  c.EnterString("Existing");
  const history = c.shell.GetUndoManager().GetUndoActionCount();
  c.StartInput(ScInputMode.SC_INPUT_TABLE);
  c.StartInput(ScInputMode.SC_INPUT_TOP, "+SUM(");
  expect(c.inputHandler.IsFormulaMode()).toBe(false);
  expect(c.inputSelection).toEqual([5, 5]);
  c.StartInput(ScInputMode.SC_INPUT_TOP, "=SUM(");
  expect(c.inputHandler.IsFormulaMode()).toBe(true);
  c.PointReference(new ScAddress(1, 1, 0));
  expect(c.Input()).toBe("=SUM(B2");
  expect(c.inputSelection).toEqual([5, 7]);
  expect(c.shell.GetUndoManager().GetUndoActionCount()).toBe(history);
  c.Cancel();
  expect(c.Input()).toBe("Existing");
  c.Close();
});
