/** Runs one native public operation from the captured protocol. @param iterator - Actual rule iterator. @param op - Source operation and optional offset. @returns Result, selected position and native status. */
function apply(iterator: RuleBasedBreakIterator, op: string): string {
  const offset = Number(op.slice(1));
  let result: number;
  switch (op[0]) {
    case "f":
      result = iterator.first();
      break;
    case "l":
      result = iterator.last();
      break;
    case "p":
      result = iterator.previous();
      break;
    case "n":
      result = iterator.next(offset);
      break;
    case ">":
      result = iterator.following(offset);
      break;
    case "<":
      result = iterator.preceding(offset);
      break;
    default:
      result = Number(iterator.isBoundary(offset));
  }
  return `${result}:${iterator.current()}:${iterator.getRuleStatus()}`;
}

