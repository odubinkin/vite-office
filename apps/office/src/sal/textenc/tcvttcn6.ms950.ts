/** Binds one original lead-table entry. @param uni - Single-byte Unicode value. @param start - First trail byte. @param end - Last trail byte. @param table - Original forward pointer. @returns Immutable source entry. */
function lead(
  uni: number,
  start: number,
  end: number,
  table: readonly number[] | null,
): ImplDBCSToUniLeadTab {
  return Object.freeze({
    mnUniChar: uni,
    mnTrailStart: start,
    mnTrailEnd: end,
    mpToUniTrailTab: table,
  });
}

/** Binds one original reverse-high entry. @param start - First low byte. @param end - Last low byte. @param table - Original reverse pointer. @returns Immutable source entry. */
