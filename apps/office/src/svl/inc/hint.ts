/** Native base notification value; derived hints carry their own data. */
export class SfxHint {
  private mnId: SfxHintId;
  /** Constructs the native default, explicit ID or copy value. @param source - Native ID or copied hint. @returns New hint value. */
  public constructor(source: SfxHintId | SfxHint = SfxHintId.NONE) {
    this.mnId = source instanceof SfxHint ? source.mnId : source;
  }
  /** Native value assignment. JS references erase the separate C++ move overload. @param source - Copied hint. @returns This value. */
  public assign(source: SfxHint): this {
    this.mnId = source.mnId;
    return this;
  }
  /** Original hint discriminator. @returns Hint ID. */
  public GetId(): SfxHintId {
    return this.mnId;
  }
}
