/** Resolves the original English resource for the first matching LanguageType. @param language - Native language identity. @returns Source text when the ID has a resource. */
export function getLanguageName(language: number): string | undefined {
  const id = getReplacementForObsoleteLanguage(language);
  return languageEntries.find(
    /** Compares the native ID in source order. @param entry - Language row. @returns Whether the ID matches. */
    ([candidate]) => candidate === id,
  )?.[1];
}
