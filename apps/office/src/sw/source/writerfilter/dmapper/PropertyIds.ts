const nativeNames = new Map<PropertyIds, OUString>();
/** Borrows the original static name; unknown IDs share the existing native empty string. @param id - Original ID. @returns Static native name. */
export function getPropertyName(id: PropertyIds): OUStringConstReference {
  const text = names.get(id);
  if (text === undefined) return SharedString.EMPTY_STRING;
  let value = nativeNames.get(id);
  if (value === undefined) {
    value = new OUString(
      Uint16Array.from(
        text.split(""),
        /** Copies one UTF16 unit. @param c - Unit. @returns Code. */ (c) => c.charCodeAt(0),
      ),
      text.length,
    );
    nativeNames.set(id, value);
  }
  return value;
}
/** Original character-property sentinel interval. @param id - Property. @returns Classification. */
export function isCharacterProperty(id: PropertyIds): boolean {
  return id > PropertyIds.PROP_CHARACTER_STYLES && id < PropertyIds.PROP_CHARACTER_END;
}
/** Original paragraph-property interval plus fill-color exceptions. @param id - Property. @returns Classification. */
export function isParagraphProperty(id: PropertyIds): boolean {
  return (
    (id >= PropertyIds.PROP_PARA_ADJUST && id <= PropertyIds.PROP_PARA_WIDOWS) ||
    id === PropertyIds.PROP_FILL_COLOR ||
    id === PropertyIds.PROP_FILL_COMPLEX_COLOR
  );
}
