/** Source reserved Writer names include the empty target of unmapped Word builtins. */
const ReservedStyleNames: ReadonlySet<string> = new Set(StyleNameMap.values());

/** The name-conversion value boundary of Writer's native document mapper. */
// eslint-disable-next-line @typescript-eslint/no-extraneous-class -- Preserve the original static StyleSheetTable::ConvertStyleName owner without fabricating the desktop mapper.
export class StyleSheetTable {
  /** Converts one Word style name, preserving builtin recognition and user suffixes. @param name - Incoming Word name. @returns Converted Writer name and whether the source table recognizes it. */
  public static ConvertStyleName(name: string): readonly [string, boolean] {
    const converted = StyleNameMap.get(name);
    if (converted !== undefined && converted.length > 0) return [converted, true];
    return [
      ReservedStyleNames.has(name) || name.endsWith(" (WW)") ? `${name} (WW)` : name,
      StyleNameMap.has(name),
    ];
  }
}
