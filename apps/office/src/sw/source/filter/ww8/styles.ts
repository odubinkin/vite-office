/** Original unsigned16 sti lookup returns null outside the builtin range. @param id - Native style identity. @returns Original name or undefined for null. */
export function GetEnglishNameFromSti(id: number): string | undefined {
  id &= 0xffff;
  return id >= sti.stiMax ? undefined : names[id];
}
