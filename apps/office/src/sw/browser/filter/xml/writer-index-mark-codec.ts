/** @fileoverview Transfers Writer TOX hints with their original paragraph and registered type. */
import { CH_TXTATR_INWORD } from "../../../inc/hintids";
import { SetAttrMode } from "../../../inc/swtypes";
import { MAXLEVEL, SwTOXMark, TOXTypes } from "../../../source/core/tox/tox";
import { SwTextTOXMark } from "../../../source/core/txtnode/atrtox";
import type { SwTextNode } from "../../../source/core/txtnode/ndtxt";

/** Primitive paragraph-owned index mark record. */
export interface WriterIndexMarkRecord {
  readonly start: number;
  readonly end?: number;
  readonly type: TOXTypes;
  readonly typeName: string;
  readonly alternativeText: string;
  readonly primaryKey: string;
  readonly secondaryKey: string;
  readonly primaryKeyReading: string;
  readonly secondaryKeyReading: string;
  readonly textReading: string;
  readonly level: number;
  readonly mainEntry: boolean;
  readonly autoGenerated: boolean;
  readonly bookmarkName: string;
}

/** Copies connected index hint values in native start order. @param node - Paragraph. @returns Detached records. */
export function encodeIndexMarks(node: SwTextNode): readonly WriterIndexMarkRecord[] {
  const records: WriterIndexMarkRecord[] = [];
  for (const hint of node.GetpSwpHints()?.GetIndexMarks() ?? []) {
    const mark = hint.GetAttr();
    const type = mark.type;
    if (!type) throw new Error("Writer index mark is missing its type.");
    const end = hint.GetEnd();
    records.push({
      start: hint.GetStart(),
      ...(end === undefined ? {} : { end }),
      type: type.type,
      typeName: type.name,
      alternativeText: mark.alternativeText,
      primaryKey: mark.primaryKey,
      secondaryKey: mark.secondaryKey,
      primaryKeyReading: mark.primaryKeyReading,
      secondaryKeyReading: mark.secondaryKeyReading,
      textReading: mark.textReading,
      level: mark.level,
      mainEntry: mark.mainEntry,
      autoGenerated: mark.autoGenerated,
      bookmarkName: mark.bookmarkName,
    });
  }
  return records;
}

/** Rebinds native hints against existing point dummy characters and range positions. @param node - Restored paragraph. @param records - Optional original index hint records. @returns Nothing. */
export function decodeIndexMarks(
  node: SwTextNode,
  records: readonly WriterIndexMarkRecord[] | undefined,
): void {
  if (records === undefined) return;
  if (!Array.isArray(records)) throw new Error("Stored Writer index marks are invalid.");
  for (const record of records as readonly WriterIndexMarkRecord[]) {
    if (
      !record ||
      (record.type !== TOXTypes.Content &&
        record.type !== TOXTypes.User &&
        record.type !== TOXTypes.Index) ||
      !Number.isInteger(record.level) ||
      record.level < 0 ||
      record.level > MAXLEVEL ||
      !Number.isInteger(record.start) ||
      record.start < 0 ||
      record.start > node.Len() ||
      typeof record.mainEntry !== "boolean" ||
      typeof record.autoGenerated !== "boolean" ||
      [
        record.typeName,
        record.alternativeText,
        record.primaryKey,
        record.secondaryKey,
        record.primaryKeyReading,
        record.secondaryKeyReading,
        record.textReading,
        record.bookmarkName,
      ].some((value) => typeof value !== "string") ||
      (record.end === undefined
        ? !record.alternativeText || node.GetText()[record.start] !== CH_TXTATR_INWORD
        : record.alternativeText ||
          !Number.isInteger(record.end) ||
          record.end < record.start ||
          record.end > node.Len())
    )
      throw new Error("Stored Writer index mark is invalid.");

    const mark = new SwTOXMark(node.GetDoc().GetTOXType(record.type, record.typeName));
    mark.alternativeText = record.alternativeText;
    mark.primaryKey = record.primaryKey;
    mark.secondaryKey = record.secondaryKey;
    mark.primaryKeyReading = record.primaryKeyReading;
    mark.secondaryKeyReading = record.secondaryKeyReading;
    mark.textReading = record.textReading;
    mark.level = record.level;
    mark.mainEntry = record.mainEntry;
    mark.autoGenerated = record.autoGenerated;
    mark.bookmarkName = record.bookmarkName;
    const hint = new SwTextTOXMark(mark, record.start, record.end);
    if (!node.InsertHint(hint, SetAttrMode.NOTXTATRCHR))
      throw new Error("Stored Writer index mark could not be attached.");
  }
}
