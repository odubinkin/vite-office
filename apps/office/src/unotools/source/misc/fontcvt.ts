/** Immutable native table conversion responsibility; unrelated recode functions/fonts are unrepresented. */
export class ConvertChar {
  /** Binds an immutable supported import table. @param table - Native224slot table. @returns Converter. */
  public constructor(private readonly table: readonly number[]) {}
  /** Recodes the native sal_Unicode value, retaining unavailable out-of-range symbols. @param character - Native scalar narrowed to uint16. @returns Native mapped scalar. */
  public RecodeChar(character: number): number {
    const original = character & 0xffff;
    let index = original;
    if (index & 0xff00) index = (index - 0xf000) & 0xffff;
    if (index >= 0x20 && index <= 0xff) return this.table[index - 0x20] || 0xe12c;
    return original;
  }
}
const starBats = Object.freeze(new ConvertChar(aStarBatsTab));
const starMath = Object.freeze(new ConvertChar(aStarMathTab));
/** Resolves the two native import-only symbol converters; no broader conversion API is claimed. @param family - Native supported family. @returns Immutable native converter. */
export function createLegacySymbolImportConverter(
  family: "StarBats" | "StarMath",
): Readonly<ConvertChar> {
  return family === "StarBats" ? starBats : starMath;
}
